// ---------------------------------------------------------------------------
// Chart of authority for procurement: the single list of who may do what, who approves, and what must stay apart.
// The screens read it, and each rule names the permission the server enforces. Amount limits are not part of the
// requirement stage (no prices exist yet); they are added here when Quotations, Purchase Requisitions and Purchase
// Orders are built, so that every value-bearing action has an approval ladder before it goes live.
// ---------------------------------------------------------------------------

export interface AuthorityRule {
    key: string;
    submodule: string;
    action: string;
    /** Permission the server requires (null: any signed-in user of the organization). */
    permission: string | null;
    who: string;
    approval: string;
    separation: string;
    limit: string;
    /** 'placeholder': the roles and rule exist, the function is not built yet. */
    status?: 'live' | 'placeholder';
}

