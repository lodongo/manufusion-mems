export const BANK_TYPES = ['central', 'commercial', 'islamic', 'development', 'microfinance', 'regional'];

export interface BankDefault {
    id: string;
    countryCode: string;
    countryName: string;
    name: string;
    shortName: string;
    type: string;
    swiftCode: string;
    website: string;
    active: boolean;
    verified: boolean;
}

export const COUNTRY_NAMES = new Map(AFRICAN_COUNTRIES.map((c) => [c.iso2, c.name]));

export function bankId(countryCode: string, name: string): string {
    const slug = name
        .toLowerCase()
        .replace(/&/g, 'and')
        .replace(/[^a-z0-9]+/g, '_')
        .replace(/^_+|_+$/g, '');
    return `${countryCode}_${slug}`.slice(0, 90);
}

const TYPE_ORDER = new Map(BANK_TYPES.map((t, i) => [t, i]));

export function sortBanks<T extends { countryName?: unknown; type?: unknown; name?: unknown }>(items: T[]): T[] {
    return [...items].sort(
        (a, b) =>
            String(a.countryName).localeCompare(String(b.countryName)) ||
            (TYPE_ORDER.get(String(a.type)) ?? 9) - (TYPE_ORDER.get(String(b.type)) ?? 9) ||
            String(a.name).localeCompare(String(b.name))
    );
}

export const AFRICAN_BANKS: BankDefault[] = sortBanks(
    ROWS.map(([countryCode, name, shortName, type, swiftCode]) => ({
        id: bankId(countryCode, name),
        countryCode,
        countryName: COUNTRY_NAMES.get(countryCode) ?? countryCode,
        name,
        shortName,
        type,
        swiftCode,
        website: '',
        active: true,
        verified: false,
    }))
);
