import { commitChecked, getDoc, HttpError, listDocs, nextSequence, nowIso, str } from './core';
import { classifiedMaterialPrefix } from './materialNumbering';

/**
 * Three linked material numbers:
 *  - request number: NWREQ_ (new material) or EXREQ_ (warehouse extension), the document key of the request;
 *  - master data number: MSTD_, issued once at final creation approval;
 *  - stores material number: the operational code used in every warehouse, issued in the same approval commit.
 *    Integrated catalogues give it their classification pattern (STR-MEC-BRG-000001); otherwise it is the
 *    material category code followed by six digits (MECH000012). This restores the numbering used before MSTD.
 * Every record carries all three, and a stores number is never a request or master number.
 *
 * Request identities and approved material-master identity.
 * Counters are generated by Firestore atomic increment on system/counters.
 * Reservation and material updates are committed atomically with preconditions.
 * Request IDs remain stable as foreign keys in inventory, PR and extension records;
 * the MSTD_ number is the externally visible approved master identity.
 */
export type MaterialIdentityKind = 'NWREQ' | 'EXREQ' | 'MSTD';
const sequenceFields:Record<MaterialIdentityKind,string>={
    NWREQ:'materialNewRequestSequence',
    EXREQ:'materialExtensionRequestSequence',
    MSTD:'materialMasterDataSequence',
};
const MAX=999_999_999;

export function materialIdentity(kind:MaterialIdentityKind,n:number):string{
    if(!Number.isSafeInteger(n)||n<1||n>MAX)throw new HttpError(409,kind+' nine-digit number range exhausted.');
    return kind+'_'+String(n).padStart(9,'0');
}
export function validMaterialRequestId(id:string):boolean{
    // Historical request IDs remain editable only while they are genuine drafts.
    return /^(?:NWREQ_\d{9}|MAT-[A-Za-z0-9-]+)$/.test(id);
}

export type StoresNumberPlan = { prefix: string; separator: '-' | ''; scheme: 'CLASSIFIED-SEQ6' | 'CATEGORY-SEQ6' };
/** The stores numbering plan of a material: its catalogue classification pattern, else its category code. */
export function storesNumberPlan(material: Record<string, unknown>, template?: Record<string, unknown>): StoresNumberPlan {
    const classified = classifiedMaterialPrefix(template);
    if (classified) return { prefix: classified, separator: '-', scheme: 'CLASSIFIED-SEQ6' };
    const category = str(material.categoryCode).trim().toUpperCase().replace(/[^A-Z0-9]/g, '').slice(0, 20);
    if (!category) throw new HttpError(409, 'The material has no category code, so its stores material number cannot be issued.');
    return { prefix: category, separator: '', scheme: 'CATEGORY-SEQ6' };
}
export const storesNumberOf = (plan: StoresNumberPlan, n: number) => plan.prefix + plan.separator + String(n).padStart(6, '0');
const SYSTEM_NUMBER = /^(?:MSTD|NWREQ|EXREQ)_\d{9}$|^MAT-/;
/** A stores number is conforming when it is not a request or master number and has the stores shape. */
export function conformingStoresNumber(n: unknown): boolean {
    const v = str(n);
    if (!v || SYSTEM_NUMBER.test(v)) return false;
    return /^[A-Z0-9]{2,5}-[A-Z0-9]{2,8}-[A-Z0-9]{2,8}-\d{6}$/.test(v) || /^[A-Z0-9]{1,20}\d{6}$/.test(v);
}
/** Every number a material has been known by: current stores, master, request and earlier aliases. */
export function materialNumberKeys(id: string, d: Record<string, unknown>): string[] {
    const aliases = Array.isArray(d.materialNumberAliases) ? d.materialNumberAliases.map(str) : [];
    return [...new Set([str(d.materialNumber), str(d.masterDataId), str(d.requestId) || id, str(d.previousMaterialNumber), ...aliases].filter(Boolean))];
}
const sequenceOf = (plan: StoresNumberPlan, v: string): number => {
    const head = plan.prefix + plan.separator;
    if (!v.startsWith(head)) return 0;
    const tail = v.slice(head.length);
    return /^\d{6}$/.test(tail) ? Number(tail) : 0;
};
/**
 * The next free stores sequence for a prefix. The counter document is authoritative; when it does not exist yet
 * it is seeded from every number already reserved or held, so legacy numbers are never issued twice.
 */
async function storesCounter(orgId: string, plan: StoresNumberPlan) {
    const root = 'organizations/' + orgId;
    const counterPath = root + '/material_number_counters/' + plan.prefix;
    const counter = await getDoc(counterPath);
    let last = Number(counter?.data.lastSequence) || 0;
    if (!counter) {
        const [reservations, materials] = await Promise.all([listDocs(root + '/material_number_reservations'), listDocs(root + '/materials')]);
        for (const r of reservations) last = Math.max(last, sequenceOf(plan, str(r.data.materialNumber) || r.id), sequenceOf(plan, r.id.replace(plan.prefix + '-', plan.prefix)));
        for (const m of materials) for (const k of materialNumberKeys(m.id, m.data)) last = Math.max(last, sequenceOf(plan, k));
    }
    if (!Number.isSafeInteger(last) || last < 0 || last >= 999999) throw new HttpError(409, 'The stores number range of ' + plan.prefix + ' is exhausted.');
    return { counterPath, counter, next: last + 1 };
}

/**
 * A fresh numbered request and its reservation are created in one DB commit.
 * Retrying after contention allocates another sequence (gaps are intentional,
 * uniqueness is more important than gapless numbering).
 */
export async function createNumberedMaterialRequest(args:{
    orgId:string;kind:'NWREQ'|'EXREQ';collection:'materials'|'material_extensions';
    data:Record<string,unknown>;actorUid:string;
}):Promise<string>{
    const {orgId,kind,collection,data,actorUid}=args;
    for(let attempt=0;attempt<8;attempt++){
        const id=materialIdentity(kind,await nextSequence(sequenceFields[kind]));
        const root='organizations/'+orgId;
        const stamp=nowIso();
        const ok=await commitChecked([
            {path:root+'/'+collection+'/'+id,data:{
                ...data,requestId:id,requestType:kind,createdAt:data.createdAt||stamp,
            },precondition:{exists:false}},
            {path:root+'/material_identity_reservations/'+id,data:{
                id,kind,requestId:id,collection,createdBy:actorUid,createdAt:stamp,
            },precondition:{exists:false}},
        ]);
        if(ok)return id;
    }
    throw new HttpError(409,'Could not reserve a unique '+kind+' request number.');
}

/**
 * Only the final PRC-001 approval issues the MSTD_ identity. A single Firestore
 * commit changes status to approved and reserves the master ID, preventing a
 * partially-approved material without its approved master number.
 */
export async function approveWithMasterIdentity(args:{
    orgId:string;requestId:string;
    changed:Record<string,unknown>;
    updateTime:string;actorUid:string;plan:StoresNumberPlan;
}):Promise<{masterDataId:string;materialNumber:string}>{
    const {orgId,requestId,changed,updateTime,actorUid,plan}=args;
    const root='organizations/'+orgId;
    const path=root+'/materials/'+requestId;
    const current=await getDoc(path);
    if(!current||current.updateTime!==updateTime||str(current.data.status)!=='pending_approval')
        throw new HttpError(409,'Material approval has changed. Reload the request.');
    if(str(current.data.masterDataId))
        throw new HttpError(409,'This material already has an approved master identity.');
    const masterDataId=materialIdentity('MSTD',await nextSequence(sequenceFields.MSTD));
    for(let attempt=0;attempt<12;attempt++){
        const {counterPath,counter,next}=await storesCounter(orgId,plan);
        const materialNumber=storesNumberOf(plan,next);
        const stamp=nowIso();
        const earlier=str(changed.materialNumber);
        const ok=await commitChecked([
            {path,data:{...changed,requestId,masterDataId,materialNumber,
                materialNumberScheme:plan.scheme,numberAllocatedAt:stamp,numberAllocatedBy:actorUid,
                approvedBy:actorUid,
                ...(earlier&&earlier!==materialNumber?{previousMaterialNumber:earlier}:{})
            },precondition:{updateTime}},
            {path:root+'/material_identity_reservations/'+masterDataId,data:{
                id:masterDataId,kind:'MSTD',materialRequestId:requestId,materialNumber,
                approvedBy:actorUid,createdAt:stamp,
            },precondition:{exists:false}},
            {path:counterPath,data:{prefix:plan.prefix,scheme:plan.scheme,lastSequence:next,lastMaterialId:requestId,updatedAt:stamp},
                precondition:counter?{updateTime:counter.updateTime}:{exists:false}},
            {path:root+'/material_number_reservations/'+materialNumber,data:{
                materialId:requestId,materialNumber,masterDataId,codePrefix:plan.prefix,sequence:next,createdBy:actorUid,createdAt:stamp,
            },precondition:{exists:false}},
        ]);
        if(ok)return {masterDataId,materialNumber};
        const latest=await getDoc(path);
        if(!latest||latest.updateTime!==updateTime)
            throw new HttpError(409,'Material changed while approving. Reload the request.');
    }
    throw new HttpError(409,'Unable to reserve the next stores material number. Retry the approval.');
}

/**
 * Gives one approved material a conforming stores number (and an MSTD number when it has none), keeping every
 * earlier number as an alias. Returns null when the material already conforms.
 */
export async function synchroniseMaterialIdentity(args:{orgId:string;materialId:string;plan:StoresNumberPlan;actorUid:string}):
    Promise<{materialId:string;from:string;materialNumber:string;masterDataId:string}|null>{
    const {orgId,materialId,plan,actorUid}=args;
    const root='organizations/'+orgId;
    const path=root+'/materials/'+materialId;
    let masterDataId='';
    for(let attempt=0;attempt<12;attempt++){
        const material=await getDoc(path);
        if(!material)throw new HttpError(404,'Material '+materialId+' not found.');
        const d=material.data;
        if(!['approved','active','disabled'].includes(str(d.status)))return null;
        const hasMaster=/^MSTD_\d{9}$/.test(str(d.masterDataId));
        if(conformingStoresNumber(d.materialNumber)&&hasMaster&&str(d.requestId))return null;
        const stamp=nowIso();
        const from=str(d.materialNumber);
        if(!hasMaster&&!masterDataId)masterDataId=materialIdentity('MSTD',await nextSequence(sequenceFields.MSTD));
        const master=hasMaster?str(d.masterDataId):masterDataId;
        const writes:Parameters<typeof commitChecked>[0]=[];
        let materialNumber=from;
        if(!conformingStoresNumber(from)){
            const {counterPath,counter,next}=await storesCounter(orgId,plan);
            materialNumber=storesNumberOf(plan,next);
            writes.push({path:counterPath,data:{prefix:plan.prefix,scheme:plan.scheme,lastSequence:next,lastMaterialId:materialId,updatedAt:stamp},
                precondition:counter?{updateTime:counter.updateTime}:{exists:false}});
            writes.push({path:root+'/material_number_reservations/'+materialNumber,data:{materialId,materialNumber,masterDataId:master,
                codePrefix:plan.prefix,sequence:next,createdBy:actorUid,createdAt:stamp,synchronisedFrom:from},precondition:{exists:false}});
        }
        if(!hasMaster)writes.push({path:root+'/material_identity_reservations/'+master,data:{id:master,kind:'MSTD',materialRequestId:materialId,
            materialNumber,createdBy:actorUid,createdAt:stamp,synchronised:true},precondition:{exists:false}});
        const aliases=[...new Set([...(Array.isArray(d.materialNumberAliases)?d.materialNumberAliases.map(str):[]),from,str(d.previousMaterialNumber)]
            .filter(x=>x&&x!==materialNumber&&x!==master&&x!==materialId))];
        writes.unshift({path,data:{...d,requestId:str(d.requestId)||materialId,masterDataId:master,materialNumber,
            materialNumberScheme:materialNumber===from?str(d.materialNumberScheme)||plan.scheme:plan.scheme,
            materialNumberAliases:aliases,numberSynchronisedAt:stamp,numberSynchronisedBy:actorUid},precondition:{updateTime:material.updateTime}});
        if(await commitChecked(writes))return {materialId,from,materialNumber,masterDataId:master};
    }
    throw new HttpError(409,'Material '+materialId+' kept changing during synchronisation. Retry.');
}
