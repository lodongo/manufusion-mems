import assert from 'node:assert/strict';
import {seed,snapshot} from './maintenance-fixture.ts';
import {maintenanceWorkGroupRoutes,workGroupResourcePool} from '../../backend/maintenanceWorkGroups.ts';
const org='wg_fixture',r='organizations/'+org;
seed(r,{modules:{MNT:true}});
for(const [id,level,parentId] of [['LE','legal_entity','root'],['SITE','site','LE'],['CC_A','cost_center','SITE'],['CC_B','cost_center','SITE'],['UNIT','equipment','CC_A']])seed(r+'/structure/'+id,{name:id,level,parentId,status:'active'});
seed(r+'/positions/TECH',{title:'Technician',status:'active'});
for(const uid of ['ADMIN','EMP_A','EMP_B'])seed('users/'+uid,{orgId:org,status:'active',firstName:uid,assignments:[{positionCode:'TECH',nodeId:'SITE',type:'primary'}]});
const call=(route,body={})=>maintenanceWorkGroupRoutes['POST /api/org/mnt/work-groups'+route][0]({uid:'ADMIN',role:'org_super_admin',orgId:org,org:snapshot(r),me:snapshot('users/ADMIN'),permissions:['*'],directPermissions:['*'],actor:{uid:'ADMIN',email:'admin@example.test'},meta:{ip:'test'},body});
const title='Maintenance Technician',specialist='Maintenance Specialist',reason='Initial reviewed group configuration';
const a=await call('/create',{name:'Group A',siteId:'SITE'}),b=await call('/create',{name:'Group B',siteId:'SITE'});
assert.equal(a.code,'WG_0001');assert.equal(b.code,'WG_0002');
assert.deepEqual(snapshot(r+'/maintenance_work_groups/'+a.id).data.costCenterIds,[]);
const master=await call('/master/save',{expectedVersion:0,roleAlignment:{[title]:['TECH'],[specialist]:['TECH']},tasks:{'MNT.assessment.edit':[title]},reason});
assert.equal(master.version,1);
const assign=(g,cc,members,extra={})=>call('/save',{id:g.id,expectedVersion:g.version,expectedMasterVersion:1,costCenterIds:cc,members,reason,...extra});
const member={uid:'EMP_A',positionCode:'TECH'};
const saved=await assign(a,['CC_A'],{[title]:[member],[specialist]:[member]});
assert.equal(saved.version,2);
await assert.rejects(()=>assign(b,['CC_A'],{[title]:[{uid:'EMP_B',positionCode:'TECH'}]}),/cost center.*already belongs/i);
await assert.rejects(()=>assign(b,['CC_B'],{[title]:[member]}),/employee.*already belongs/i);
await assert.rejects(()=>assign(b,['CC_B'],{['Maintenance Lead']:[member]}),/role must be aligned/i);
await assert.rejects(()=>assign(b,['CC_B'],{},{tasks:{}}),/only in Master setup/i);
await assert.rejects(()=>call('/master/save',{expectedVersion:1,roleAlignment:{},tasks:{},reason}),/remove or transfer/i);
const savedB=await assign(b,['CC_B'],{[title]:[{uid:'EMP_B',positionCode:'TECH'}]});
const data=await call('');
assert.equal(data.master.version,1);
assert.deepEqual(data.master.tasks['MNT.assessment.edit'],[title]);
assert.equal(data.groups.length,2);
const pool=await workGroupResourcePool(org,{id:'WO',data:{unitId:'UNIT'},updateTime:''});
assert.equal(pool.people.find(p=>p.id==='EMP_A').inWorkGroup,true);
assert.equal(pool.people.find(p=>p.id==='EMP_B').inWorkGroup,false);
await assign({...a,version:saved.version},[],{});
await assign({...b,version:savedB.version},['CC_A','CC_B'],{[title]:[member]});
assert.equal((await workGroupResourcePool(org,{id:'WO',data:{unitId:'UNIT'},updateTime:''})).group.id,b.id);
const next=await call('/create',{name:'Group C',siteId:'SITE'});assert.equal(next.code,'WG_0003');
await assert.rejects(()=>call('/save',{name:'Not through master',siteId:'SITE'}),/create new work groups in master/i);
console.log('work groups master and assignment scenario passed');
